    TRY_TO_DECIMAL(PRODUCT_HEIGHT_CM , 8 ,2) PRODUCT_HEIGHT_CM,
    TRY_TO_DECIMAL(PRODUCT_WIDTH_CM , 8 ,2) PRODUCT_WIDTH_CM
